    /// Identity binds only through a FrameState's SFI object with the
    /// matching name — a `HeapConstant[<JSFunction …>]` can be a closure of
    /// a *different* function that shares the name, and node print order
    /// guarantees nothing (found in review). A section with no such line
    /// stays honestly unidentified, with a 1-based provisional ordinal.
    #[test]
    fn turbofan_identity_requires_a_matching_framestate() {
        let idx = index(
            "\
Begin compiling method add using TurboFan
----- Graph after V8.TFInlining -----
#5:HeapConstant[0x1 <JSFunction add (sfi = 0xdead)>]()
#7:FrameState[UNOPTIMIZED_FRAME, 2, Ignore, 0x99 <SharedFunctionInfo other>](#0:Start)
#16:FrameState[UNOPTIMIZED_FRAME, 2, Ignore, 0xbeef <SharedFunctionInfo add>](#0:Start)
",
        );
        assert_eq!(
            idx.compilations[0].key.sfi,
            Addr(0xbeef),
            "the closure constant (0xdead) and the inlined frame (0x99) must not win"
        );

        let idx = index(
            "\
Begin compiling method add using TurboFan
----- Graph after V8.TFInlining -----
#6:HeapConstant[0x2 <JSFunction add (sfi = 0x42)>]()
",
        );
        assert_eq!(
            idx.compilations[0].key.sfi,
            Addr(0),
            "no FrameState, no guess"
        );
        assert_eq!(idx.compilations[0].key.ordinal, 1, "provisional, 1-based");
    }

